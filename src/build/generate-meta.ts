/**
 * A `.js`-rewritten relative import specifier from `.jsails/` to a source
 * module, given the module's class name (resolved through the model
 * convention) or its root-relative path.
 */
function relativeSpecifier(rootDir: string, classNameOrRelative: string): string {
  const relativePath = classNameOrRelative.includes('/')
    ? classNameOrRelative
    : `models/${kebab(classNameOrRelative)}.ts`;
  const absolute = join(rootDir, relativePath);
  let rel = relative(join(rootDir, META_DIR), absolute);
  if (sep === '\\') {
    rel = rel.replace(/\\/g, '/');
  }
  rel = rel.replace(/\.(tsx|ts)$/, '.js').replace(/\.(mtsx|mts)$/, '.mjs');
  if (!rel.startsWith('.')) {
    rel = './' + rel;
  }
  return rel;
}

/** Minimal kebab-case for a class name (`BlogPost` → `blog-post`). */
function kebab(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();
}

/** Code-unit string comparison; locale-independent for deterministic order. */
function compareStrings(a: string, b: string): number {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
}
