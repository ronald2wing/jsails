/** The generated artifacts, keyed by their path relative to `.jsails/`. */
export interface MetaArtifacts {
  'project-symbols.app.d.ts': string;
  'project-symbols.server.d.ts': string;
  'framework-symbols.d.ts': string;
  'framework-symbols.js': string;
  'plugin-declarations.js': string;
  'autoload.json': string;
  'models.registry.ts': string;
  'components.registry.ts': string;
}

/** Options for {@link buildMetaArtifacts}. */
export interface BuildMetaArtifactsOptions {
  /**
   * Absolute path to the framework package root, whose barrels the
   * framework-symbol scan reads. Defaults to the installed framework's own
   * root, resolved from this module.
   */
  readonly frameworkRootDir?: string;
  /**
   * Which framework subpaths project onto `globalThis`. Defaults to the
   * framework's own `jsails.plugin.json` autoload declaration (scanned from the
   * framework root at build time). A plugin's declared `autoload` is folded in
   * on top (see {@link pluginDeclarations}).
   */
  readonly declaration?: SymbolDeclaration;
  /**
   * Per-plugin declarations to fold into the projection (defaults to the inert
   * scan of the framework package's own `jsails.plugin.json` files). A plugin
   * that `autoload`s `all` admits its whole `provides` inventory; `selected`
   * admits its named `specifiers`; `none` admits nothing. These subpaths are
   * unioned with the framework declaration so they project and type-check bare.
   */
  readonly pluginDeclarations?: readonly PluginDeclaration[] | undefined;
}

/** Build every artifact string from a scan result. Pure. */
export function buildMetaArtifacts(
  meta: ProjectMeta,
  rootDir: string,
  options: BuildMetaArtifactsOptions = {},
): MetaArtifacts {
  const dts = generateProjectSymbolsDts(meta.autoload, { rootDir });
  const frameworkRootDir = options.frameworkRootDir ?? FRAMEWORK_ROOT;
  // Read source barrels in-repo (the framework's own `src/` exists) and the
  // emitted `.d.ts` barrels against an installed framework (only `dist/` ships).
  const sourceKind = existsSync(join(frameworkRootDir, 'src')) ? 'source' : 'declaration';

  // Plugin declarations: explicit override, or scan the framework package for
  // both the core declaration and first-party plugin declarations.
  const scannedDecls: readonly PluginDeclaration[] =
    options.pluginDeclarations ??
    scanPluginDeclarations({ frameworkRootDir }).map((entry) => entry.declaration);

  // The framework's own autoload: explicit override wins; otherwise read the
  // framework's `jsails.plugin.json` from the package root directly (independent
  // of the plugin-declarations override, so passing `pluginDeclarations` never
  // drops the curated framework surface). When neither is present, project none.
  let frameworkDecl: SymbolDeclaration;
  if (options.declaration !== undefined) {
    frameworkDecl = options.declaration;
  } else {
    frameworkDecl = loadFrameworkAutoloadDeclaration(frameworkRootDir);
  }

  // Plugin declarations for the union: when the declaration is an explicit
  // override, include every scanned declaration (the caller owns the whole
  // surface); otherwise exclude the framework's own declaration so it is not
  // double-counted.
  const pluginDecls: readonly PluginDeclaration[] =
    options.declaration !== undefined
      ? scannedDecls
      : scannedDecls.filter((d) => d.id !== 'jsails');

  const effectiveDeclaration = resolveSymbolDeclarations([
    frameworkDecl,
    ...pluginDecls.map(pluginAutoloadAsDeclaration),
  ]);
  const frameworkGlobals = deriveFrameworkSymbols({
    rootDir: frameworkRootDir,
    sourceKind,
    declaration: effectiveDeclaration,
  });
  return {
    'project-symbols.app.d.ts': dts['project-symbols.app.d.ts'],
    'project-symbols.server.d.ts': dts['project-symbols.server.d.ts'],
    'framework-symbols.d.ts': generateFrameworkSymbolsDts({ globals: frameworkGlobals }),
    'framework-symbols.js': emitFrameworkSymbolsModule(frameworkGlobals),
    // Emit only first-party plugin declarations — the framework's own
    // declaration is the substrate, not a plugin runtime artifact.
    'plugin-declarations.js': emitPluginDeclarationsModule(
      scannedDecls.filter((d) => d.id !== 'jsails'),
    ),
    'autoload.json': emitAutoloadJson(meta.autoload),
    'models.registry.ts': emitModelsRegistry(meta.models, rootDir),
    'components.registry.ts': emitComponentsRegistry(meta.components, rootDir),
  };
}

/**
 * A plugin declaration's autoload expressed as a `selected` declaration over its
 * admitted subpaths: `all` → every `provides` subpath, `selected` → its named
 * `specifiers`, `none`/absent → nothing.
 */
function pluginAutoloadAsDeclaration(declaration: PluginDeclaration): SymbolDeclaration {
  const autoload = declaration.autoload;
  if (autoload === undefined || autoload.mode === 'none') {
    return { mode: 'none' };
  }
  if (autoload.mode === 'all') {
    return { mode: 'selected', specifiers: declaration.provides };
  }
  return { mode: 'selected', specifiers: autoload.specifiers ?? [] };
}

/**
 * Write every artifact under `<rootDir>/.jsails/`. The only function here that
 * touches the filesystem; it creates the directory if needed and overwrites
 * each file (the directory is generated, so overwrite is correct).
 *
 * In addition to the six flat artifacts, it writes the **shim tree** under
 * `<rootDir>/.jsails/project-symbols/` plus `.jsails/project-symbols.js` (the
 * runtime half of the autoload story — see {@link writeShimTree}). The shim tree
 * imports the *compiled* modules, so `compiledRoot` (default `'dist'`) must
 * match the tsconfig `outDir`.
 */
export function writeMetaArtifacts(
  meta: ProjectMeta,
  rootDir: string,
  options: ShimTreeOptions & BuildMetaArtifactsOptions = {},
): void {
  const artifacts = buildMetaArtifacts(meta, rootDir, options);
  const dir = join(rootDir, META_DIR);
  mkdirSync(dir, { recursive: true });
  for (const [name, content] of Object.entries(artifacts)) {
    writeFileSync(join(dir, name), content, 'utf8');
  }

  const shimModules = scanShimModules(meta.autoload);
  writeShimTree(shimModules, rootDir, {
    ...options,
    collisions: meta.autoload.collisions,
  });
}

