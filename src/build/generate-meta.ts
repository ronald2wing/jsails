/**
 * Pure emitters for the generated build artifacts.
 *
 * Each function takes already-scanned data and returns a string; none touches
 * the filesystem. The writer ({@link writeMetaArtifacts}) is the only function
 * here that writes. It writes the seven flat artifacts the build step produces,
 * plus the shim tree (`.jsails/project-symbols/**` + `.jsails/project-symbols.js`)
 * emitted by {@link writeShimTree}:
 *
 * - `.jsails/project-symbols.app.d.ts` / `.jsails/project-symbols.server.d.ts` —
 *   ambient declarations making autoloaded symbols visible to `tsc` (delegated
 *   to {@link generateProjectSymbolsDts}).
 * - `.jsails/framework-symbols.d.ts` — the ambient `@jsails.*` decorator
 *   namespace and the framework-global declarations (delegated to
 *   {@link generateFrameworkSymbolsDts}).
 * - `.jsails/framework-symbols.js` — the runtime framework-symbol table the
 *   installer projects onto `globalThis` (delegated to
 *   {@link emitFrameworkSymbolsModule}). Derived from the framework's own
 *   barrels at this step, so it can never drift from them.
 * - `.jsails/autoload.json` — the autoload registry, consumed by the Vite
 *   transform at bundle time.
 * - `.jsails/models.registry.ts` — a pure-data `defineModel(...)` call per
 *   model, compiled by `tsc` and imported by `bootstrapModels()`.
 * - `.jsails/components.registry.ts` — a `registerComponent(...)` call per
 *   component, compiled by `tsc` and imported by `bootstrapComponents()`.
 *
 * The generated `.ts` files are **pure data**: they import the user's classes
 * and call the tested runtime lowering (`defineModel` / `registerComponent`).
 * No TypeORM factory, no lowering logic, lives in generated code — that keeps
 * the generated surface stable across TypeORM bumps and testable once.
 */

