// Public surface: this module is the jamal command's entry point. The planning
// flows live in `plan.ts`, the execution verbs in `exec.ts`, and the help text
// in `usage.ts`; re-export the shared seam so consumers import the same symbols
// from here as before the split.
export { JamalError, defaultJamalDeps } from './plan-command.js';
export type { JamalDeps } from './plan-command.js';

const JAMAL_OPTIONS = {
  write: { type: 'boolean', default: false },
  dir: { type: 'string' },
  target: { type: 'string', default: 'kamal' },
  detach: { type: 'boolean', default: false },
  follow: { type: 'boolean', default: false },
  'dry-run': { type: 'boolean', default: false },
  tag: { type: 'string' },
  help: { type: 'boolean', short: 'h', default: false },
  keep: { type: 'string' },
  images: { type: 'string', multiple: true },
  name: { type: 'string' },
  snapshot: { type: 'string' },
  driver: { type: 'string' },
} as const;

/**
 * Run the `jamal` command over the tokens after the `jamal` command name.
 * Resolves to a process exit code: 0 on success (including a dry run, a
 * `targets` listing, a run where files were skipped, and a clean `docker
 * compose` execution), 2 for usage errors, 1 for a generation/write failure
 * or a spawn failure, 127 when docker compose is unavailable, and the child's
 * own exit code when a compose verb fails. Help and usage paths never build
 * the registry, run a generator, or spawn a process.
 */
export async function runJamalCommand(
  args: readonly string[],
  deps: JamalDeps = defaultJamalDeps,
): Promise<number> {
  // `accessory` and `domain` own their own flag sets and positional shapes, so
  // they are routed before the shared `parseArgs` gate (which would reject their
  // flags).
  if (args[0] === 'accessory') {
    return runAccessoryCommand(deps, args.slice(1));
  }
  if (args[0] === 'domain') {
    return runDomainCommand(deps, args.slice(1));
  }
  if (args[0] === 'app') {
    return runAppCommand(deps, args.slice(1));
  }

  let parsed;
  try {
    parsed = parseArgs({
      args: [...args],
      options: JAMAL_OPTIONS,
      allowPositionals: true,
      strict: true,
    });
  } catch (error) {
    return usageError(deps, formatError(error));
  }

  const { values, positionals } = parsed;

  if (values.help) {
    deps.stdout(positionals[0] === 'deploy' ? JAMAL_DEPLOY_USAGE : JAMAL_USAGE);
    return 0;
  }

  if (positionals.length === 0 || positionals[0] === undefined) {
    return usageError(
      deps,
      'a subcommand is required (up | down | ps | logs | exec | dev | deploy | targets | accessory | app)',
    );
  }
  const subcommand = positionals[0];

  // `--dry-run` previews the engine plan; it is valid only for the kamal engine
  // (`deploy --target kamal`) and `rollback`.
  if (values['dry-run'] && subcommand !== 'deploy' && subcommand !== 'rollback') {
    return usageError(deps, '--dry-run is only valid for `jamal deploy` and `jamal rollback`');
  }

  // `--tag` names the image tag to deploy; it is valid only for `deploy`.
  if (values.tag !== undefined && subcommand !== 'deploy') {
    return usageError(deps, '--tag is only valid for `jamal deploy`');
  }

  // `deploy` routes by target: the kamal engine executes (or previews with
  // `--dry-run`), while every static/custom target only generates files.
  if (subcommand === 'deploy') {
    if (positionals.length > 1) {
      return usageError(deps, `unexpected argument: ${positionals.slice(1).join(' ')}`);
    }
    if ((values.target ?? 'kamal') === 'kamal') {
      return runDeployCommand(deps, values);
    }
    if (values.tag !== undefined) {
      return usageError(deps, '--tag is only valid for `deploy --target kamal`');
    }
    return runPlanCommand(deps, subcommand, {
      write: values.write,
      dir: values.dir,
      target: values.target,
      dryRun: values['dry-run'],
    });
  }

  // `rollback` executes by default; `--dry-run` previews it.
  if (subcommand === 'rollback') {
    if (positionals.length > 1) {
      return usageError(deps, `unexpected argument: ${positionals.slice(1).join(' ')}`);
    }
    return runRollbackCommand(deps, values);
  }

  // `status` inspects the remote server; it requires a production config.
  if (subcommand === 'status') {
    if (positionals.length > 1) {
      return usageError(deps, `unexpected argument: ${positionals.slice(1).join(' ')}`);
    }
    return runRemoteStatusVerb(deps);
  }

  // `logs`/`exec` inspect the remote container when a production config is
  // present; otherwise they drive the local Compose project as before.
  if (subcommand === 'logs' || subcommand === 'exec') {
    const remote = await routeRemoteLogsOrExec(
      deps,
      subcommand,
      positionals.slice(1),
      values,
      args,
    );
    if (remote !== undefined) {
      return remote;
    }
  }

  // Execution verbs spawn `docker compose` and take their own positional
  // shape (`logs` may carry a service name); they are routed before the
  // one-positional rule that governs the generation subcommands.
  if (isDockerVerb(subcommand)) {
    return runDockerVerb(subcommand, positionals.slice(1), values, deps);
  }

  // `exec` takes a service name plus a verbatim command after `--`; it is
  // routed before the one-positional rule so the command flags stay positional.
  if (subcommand === 'exec') {
    return runDockerExec(positionals.slice(1), args.includes('--'), values, deps);
  }

  // `registry` and `audit` subcommands load the jamal config and print a plan.
  // `prune` takes --keep and --images flags. `snapshot` takes a service name
  // and optional --name/--driver; `snapshot restore` takes a snapshot path.
  // These are pure planners: they never execute Docker, resolve secrets, or
  // open a connection.

  if (subcommand === 'registry') {
    if (positionals.length > 1) {
      return usageError(deps, `unexpected argument: ${positionals.slice(1).join(' ')}`);
    }
    return runRegistryCommand(deps);
  }

  if (subcommand === 'prune') {
    if (positionals.length > 1) {
      return usageError(deps, `unexpected argument: ${positionals.slice(1).join(' ')}`);
    }
    return runPruneCommand(deps, values);
  }

  if (subcommand === 'audit') {
    if (positionals.length > 1) {
      return usageError(deps, `unexpected argument: ${positionals.slice(1).join(' ')}`);
    }
    return runAuditCommand(deps);
  }

  if (subcommand === 'snapshot') {
    return runSnapshotCommand(deps, positionals.slice(1), values);
  }

  if (positionals.length > 1) {
    return usageError(deps, `unexpected argument: ${positionals.slice(1).join(' ')}`);
  }

  if (subcommand === 'targets') {
    return runTargets(deps);
  }

  // Everything else is a generation subcommand (`dev`, `harden`): resolve the
  // generator set and plan (or write) the file set.
  return runPlanCommand(deps, subcommand, values);
}

