/**
 * Jamal deployment command.
 *
 * Jamal wraps the deploy-generator registry behind a small, human-first CLI.
 * `jamal dev` plans the local development set (Valkey + database Docker
 * Compose); `jamal deploy` on the default Docker/SSH (kamal) engine EXECUTES a
 * production release by default (`--dry-run` prints the pure engine plan), while
 * a static hosting target (`--target vercel|netlify|cloudflare|github`, plus any
 * custom deployment generator declared in the app config's `deployments` array)
 * only generates files and requires `--write` to materialize them; the built-in
 * static targets (`vercel`/`netlify`/`cloudflare`) then EXECUTE their deploy
 * through `npx` — `github` is push-based and stays a workflow + hint. `jamal
 * targets` lists every available target without running one. Static and custom
 * targets are never deployed by jamal — the generated files are deployed with
 * the host's own CLI (e.g. `npx vercel deploy --prod`). `rollback` executes by
 * default with `--dry-run` as its preview.
 *
 * Custom targets are merged after the built-ins by loading `jsails.app.js`
 * (trusted app code) when it exists; a custom name that collides with a
 * built-in generator id is rejected.
 *
 * Production is the DEFAULT: `jamal deploy` runs a production release (Kamal),
 * or generates a static host's files via `--target`, while `jamal dev` is the
 * explicit local-development override. Jamal never auto-detects an environment
 * — the user names it. The Sail-like execution verbs (`up`, `down`, `ps`,
 * `logs`) drive the local Compose project generated by `dev --write` and are
 * the one place jamal spawns `docker compose`; see `src/jamal/docker.ts`.
 */

