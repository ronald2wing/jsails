/** Load the jamal config for the new planner subcommands, reporting failures. */
async function loadConfigForSubcommand(deps: JamalDeps): Promise<JamalConfig | undefined> {
  const loader = deps.loadJamalConfig ?? ((dir: string) => loadJamalConfig(dir));
  try {
    return await loader(deps.cwd);
  } catch (error) {
    deps.stderr(`jsails: ${formatError(error)}`);
    return undefined;
  }
}

/** `jamal registry [login]`: print the docker login argv. Never executes. */
async function runRegistryCommand(deps: JamalDeps): Promise<number> {
  const config = await loadConfigForSubcommand(deps);
  if (config === undefined) {
    return 1;
  }

  let plan: RegistryLoginPlan;
  try {
    plan = planRegistryLogin(config);
  } catch (error) {
    deps.stderr(`jsails: ${formatError(error)}`);
    return 1;
  }

  deps.stdout(formatRegistryLoginPlan(plan));
  return 0;
}

/** The parsed values the `jamal prune` / `jamal snapshot` commands read. */
interface ExtraPlanValues {
  readonly keep?: string;
  readonly images?: string[] | undefined;
  readonly name?: string;
  readonly snapshot?: string;
  readonly driver?: string;
}

/** `jamal prune --keep <n> [--images <ref>...]`: plan image removal. Never executes. */
async function runPruneCommand(deps: JamalDeps, values: ExtraPlanValues): Promise<number> {
  if (values.keep === undefined) {
    return usageError(deps, '--keep <n> is required for `jamal prune`');
  }
  const keep = Number(values.keep);
  if (Number.isNaN(keep) || !Number.isFinite(keep) || !Number.isInteger(keep) || keep < 1) {
    return usageError(deps, '--keep must be a positive integer >= 1');
  }

  const images: ImageRef[] = values.images ?? [];
  if (images.length === 0) {
    deps.stdout('No images to prune.');
    return 0;
  }

  let plan: ReturnType<typeof planPrune>;
  try {
    plan = planPrune({ keep, images });
  } catch (error) {
    deps.stderr(`jsails: ${formatError(error)}`);
    return 1;
  }

  deps.stdout(formatPrunePlan(plan));
  return 0;
}

/** `jamal audit`: print a security checklist. Never executes. */
async function runAuditCommand(deps: JamalDeps): Promise<number> {
  const config = await loadConfigForSubcommand(deps);
  if (config === undefined) {
    return 1;
  }

  const plan = planAudit(config);
  deps.stdout(formatAuditPlan(plan));
  return 0;
}

/** `jamal snapshot [restore] <service> ...`: print the dump/restore argv. Never executes. */
async function runSnapshotCommand(
  deps: JamalDeps,
  rest: readonly string[],
  values: ExtraPlanValues,
): Promise<number> {
  if (rest.length === 0) {
    return usageError(
      deps,
      'a service name is required: `jamal snapshot <service>` or `jamal snapshot restore <service> --snapshot <path>`',
    );
  }

  const verb = rest[0];
  if (verb === 'restore') {
    return runSnapshotRestoreCommand(deps, rest.slice(1), values);
  }

  // Snapshot (create): rest[0] is the service name.
  const service = verb as string;
  const driver = parseSnapshotDriver(values.driver);

  let plan: ReturnType<typeof planSnapshot>;
  try {
    plan = planSnapshot({ service, name: values.name, driver });
  } catch (error) {
    deps.stderr(`jsails: ${formatError(error)}`);
    return 1;
  }

  deps.stdout(formatSnapshotPlan(plan));
  return 0;
}

/** `jamal snapshot restore <service> --snapshot <path> [--driver <driver>]`. */
async function runSnapshotRestoreCommand(
  deps: JamalDeps,
  rest: readonly string[],
  values: ExtraPlanValues,
): Promise<number> {
  const service = rest[0];
  if (service === undefined || service === '') {
    return usageError(deps, 'a service name is required for `jamal snapshot restore <service>`');
  }
  if (rest.length > 1) {
    return usageError(deps, `unexpected argument: ${rest.slice(1).join(' ')}`);
  }

  if (values.snapshot === undefined || values.snapshot === '') {
    return usageError(deps, '--snapshot <path> is required for `jamal snapshot restore`');
  }

  const driver = parseSnapshotDriver(values.driver);

  let plan: ReturnType<typeof planRestore>;
  try {
    plan = planRestore({ service, snapshotPath: values.snapshot, driver });
  } catch (error) {
    deps.stderr(`jsails: ${formatError(error)}`);
    return 1;
  }

  deps.stdout(formatSnapshotPlan(plan));
  return 0;
}

/** Parse the --driver flag into a SnapshotDriver, defaulting to `mariadb`. */
function parseSnapshotDriver(raw: string | undefined): SnapshotDriver {
  if (raw === 'postgres') {
    return 'postgres';
  }
  return 'mariadb';
}
