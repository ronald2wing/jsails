/**
 * Pure emitter for the folded plugin-declaration runtime artifact.
 *
 * `build:meta` folds every discovered plugin declaration (its own `autoload`
 * surface, `provides` inventory, `symbols`, and declared dependencies) into
 * `.jsails/plugin-declarations.js` — the runtime half the assembly consumer
 * reads, exactly as `.jsails/framework-symbols.js` carries the framework's
 * surface and `.jsails/project-symbols.js` carries the project's. One scan at
 * build; both the ambient `.d.ts` and the runtime read its output.
 *
 * The emitted module is **pure data**: a frozen `PluginDeclaration[]` literal.
 * The runtime consumer owns projection; this file owns nothing but the table.
 */

import type {
  PluginDeclaration,
  PluginDeclarationDependency,
  PluginSymbol,
} from '../plugins/declaration.js';

/** The generated plugin-declarations entry, relative to the project root. */
export const PLUGIN_DECLARATIONS_ENTRY = '.jsails/plugin-declarations.js';

/** A literal rendering of a plugin declaration, escaped and frozen. */
function renderEntry(declaration: PluginDeclaration): string {
  const autoload = declaration.autoload;
  const autoloadLit =
    autoload === undefined
      ? 'undefined'
      : autoload.mode === 'none' || autoload.mode === 'all'
        ? `Object.freeze({ mode: ${quote(autoload.mode)} })`
        : `Object.freeze({ mode: 'selected', plugins: ${renderStringArray(
            autoload.plugins ?? [],
          )}, specifiers: ${renderStringArray(autoload.specifiers ?? [])} })`;

  return `  Object.freeze({
    id: ${quote(declaration.id)},
    provides: Object.freeze(${renderStringArray(declaration.provides)}),
    autoload: ${autoloadLit},
    symbols: ${renderSymbols(declaration.symbols)},
    plugins: ${renderDependencies(declaration.plugins)},
  }),`;
}

function renderSymbols(symbols: readonly PluginSymbol[] | undefined): string {
  if (symbols === undefined) {
    return 'undefined';
  }
  return `Object.freeze([${symbols
    .map((s) => `Object.freeze({ name: ${quote(s.name)}, specifier: ${quote(s.specifier)} })`)
    .join(', ')}])`;
}

function renderDependencies(deps: readonly PluginDeclarationDependency[] | undefined): string {
  if (deps === undefined) {
    return 'undefined';
  }
  return `Object.freeze([${deps.map((d) => `Object.freeze({ id: ${quote(d.id)} })`).join(', ')}])`;
}

/** A frozen array literal of string values. */
function renderStringArray(values: readonly string[]): string {
  return `Object.freeze([${values.map(quote).join(', ')}])`;
}

/** Double-quote a string, escaping the characters that can appear in an id/subpath. */
function quote(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/**
 * Emit `.jsails/plugin-declarations.js`: a frozen list of the folded plugin
 * declarations. Deterministic — entries keep the caller's id-sorted order.
 */
export function emitPluginDeclarationsModule(declarations: readonly PluginDeclaration[]): string {
  const entries = declarations.map(renderEntry).join('\n');
  const body = entries.length > 0 ? `[\n${entries}\n]` : '[]';
  return `// AUTO-GENERATED by jsails build:meta. Do not edit.\n\nexport const PLUGIN_DECLARATIONS = Object.freeze(${body});\n`;
}
