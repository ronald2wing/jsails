/**
 * Pure string builder for ambient type declarations that make auto-imported
 * symbols visible to the type checker without manual imports.
 *
 * Reads a frozen C1 {@link AutoloadRegistry} (via {@code registry.byName}) and
 * emits two context-keyed {@code .d.ts} files: one for the app context
 * (client+server, symbols from {@code app/} and {@code shared/}) and one for
 * the server-only context ({@code server/utils/}).
 *
 * Each symbol is declared as a **split value + type pair** so both a value use
 * (`new Author()`) and a type use (`declare author: Author`) resolve without an
 * import. A value-only `declare const` would leave the type side undefined
 * (`TS2749`).
 *
 * The emitter is pure: no I/O, no filesystem, no connection.
 */

import { relative, sep } from 'node:path';

import type { AutoloadContext, AutoloadRegistry } from './project-symbols-scan.js';
import { deriveFrameworkSymbolNamespaceKeys } from '../symbols/framework-symbols.js';

/* ------------------------------------------------------------------ */
/*  Options                                                            */
/* ------------------------------------------------------------------ */

export interface GenerateProjectSymbolsDtsOptions {
  /** The project root directory — used to compute relative paths from {@code .jsails/}. */
  readonly rootDir: string;
}

/* ------------------------------------------------------------------ */
/*  Output shape                                                      */
/* ------------------------------------------------------------------ */

/** The two generated declaration files. */
export interface ProjectSymbolsDtsFiles {
  'project-symbols.app.d.ts': string;
  'project-symbols.server.d.ts': string;
}

/* ------------------------------------------------------------------ */
/*  Header                                                             */
/* ------------------------------------------------------------------ */

const HEADER = '// AUTO-GENERATED by @jsails/compiler. Do not edit.\n\n';

/* ------------------------------------------------------------------ */
/*  Main entry point                                                   */
/* ------------------------------------------------------------------ */

/**
 * Generate the pair of ambient declaration files. If the registry holds no
 * symbols for a context, that file still emits a valid empty stub ({@code
 * declare global {} export {};}) so the tsconfig reference never points at a
 * missing file.
 */
export function generateProjectSymbolsDts(
  registry: AutoloadRegistry,
  options: GenerateProjectSymbolsDtsOptions,
): ProjectSymbolsDtsFiles {
  const jsailsDir = options.rootDir; // .jsails/ is at project root

  return {
    'project-symbols.app.d.ts': emitContext(registry, 'app', jsailsDir),
    'project-symbols.server.d.ts': emitContext(registry, 'server', jsailsDir),
  };
}

/* ------------------------------------------------------------------ */
/*  Per-context emission                                               */
/* ------------------------------------------------------------------ */

function emitContext(
  registry: AutoloadRegistry,
  context: AutoloadContext,
  jsailsDir: string,
): string {
  // Collect every symbol for this context, deduplicated by name.
  const lines: { name: string; relative: string }[] = [];

  for (const [name, contexts] of registry.byName) {
    const symbol = contexts.get(context);
    if (symbol === undefined) continue;

    const rel = relativeToJsails(jsailsDir, symbol.file);
    lines.push({ name, relative: rel });
  }

  // Deterministic: sort by name.
  lines.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

  // Each symbol is emitted as a split value + type pair. A `declare const X` is
  // a value, not a type, so a bare `declare author: Author` would fail
  // (`TS2749`); the paired `declare type X` supplies the type side. Both sides
  // query the same export: `typeof import(spec).X` is the constructor/function
  // type (value side), and `import(spec).X` is the instance type (type side for
  // a class) or the function type (type side for a function).
  const winnerBody =
    lines.length === 0
      ? ''
      : lines
          .map(
            (l) =>
              `  const ${l.name}: typeof import('${l.relative}').${l.name};\n` +
              `  type ${l.name} = import('${l.relative}').${l.name};`,
          )
          .join('\n') + '\n';

  // Colliding symbols: a namespace type declaration for each distinct key.
  const namespaceBody = buildNamespaceDecls(registry, context, jsailsDir);

  const body = winnerBody + namespaceBody;
  return `${HEADER}declare global {\n${body}}\nexport {};\n`;
}

/* ------------------------------------------------------------------ */
/*  Namespace type declarations (collision resolution)                 */
/* ------------------------------------------------------------------ */

/**
 * Strip a source extension from a posix-relative path, producing the specifier
 * form {@link deriveFrameworkSymbolNamespaceKeys} expects. `app/models/post.ts` → `app/models/post`.
 */
function modulePathStripped(jsailsDir: string, absolute: string): string {
  let rel = relative(jsailsDir, absolute);
  if (sep === '\\') {
    rel = rel.replace(/\\/g, '/');
  }
  return rel.replace(/\.(tsx|ts)$/, '').replace(/\.(mtsx|mts)$/, '');
}

/**
 * Build namespace type declarations for colliding project symbols.
 *
 * For each collision whose winner lives in the given context, derives a
 * namespace key from the winner's extension-stripped posix-relative path (the
 * same key the shim tree uses at runtime), and emits a typed namespace object
 * inside `declare global`. Bare winner pairs are unchanged — this only adds
 * the object path for consumers that prefer `<key>.<name>`.
 *
 * Returns `''` when there are no collisions, keeping the output byte-identical.
 */
function buildNamespaceDecls(
  registry: AutoloadRegistry,
  context: AutoloadContext,
  jsailsDir: string,
): string {
  if (registry.collisions.size === 0) {
    return '';
  }

  // Collect every winner path (posix-relative, extension-stripped) and the
  // entries that this context contributes.
  const winnerPaths: string[] = [];
  const entriesByPath = new Map<string, { name: string; importSpecifier: string }[]>();

  for (const [name, symbols] of registry.collisions) {
    const winner = symbols[0];
    if (winner === undefined) continue;
    // Only emit the namespace decl when the winner is in this context.
    if (winner.context !== context) continue;

    const path = modulePathStripped(jsailsDir, winner.file);
    winnerPaths.push(path);
    let entries = entriesByPath.get(path);
    if (entries === undefined) {
      entries = [];
      entriesByPath.set(path, entries);
    }
    const rel = relativeToJsails(jsailsDir, winner.file);
    entries.push({ name, importSpecifier: rel });
  }

  if (winnerPaths.length === 0) return '';

  const keys = deriveFrameworkSymbolNamespaceKeys(winnerPaths);

  // Merge entries whose paths resolve to the same key.
  const groupsByKey = new Map<string, { name: string; importSpecifier: string }[]>();
  for (const [path, entries] of entriesByPath) {
    const key = keys.get(path);
    if (key === undefined) continue;
    let group = groupsByKey.get(key);
    if (group === undefined) {
      group = [];
      groupsByKey.set(key, group);
    }
    group.push(...entries);
  }

  const sortedKeys = [...groupsByKey.keys()].sort();
  const lines: string[] = [];
  for (const key of sortedKeys) {
    const group = groupsByKey.get(key);
    if (group === undefined) continue;
    // Deduplicate by name, sort.
    const unique = dedupeByName(group);
    const members = unique
      .map((e) => `    ${e.name}: typeof import('${e.importSpecifier}').${e.name};`)
      .join('\n');
    lines.push(`  const ${key}: {\n${members}\n  };`);
  }

  return lines.join('\n') + '\n';
}

/** Deduplicate entries by name, keeping the first, sorted by name. */
function dedupeByName(
  entries: readonly { name: string; importSpecifier: string }[],
): readonly { name: string; importSpecifier: string }[] {
  const seen = new Set<string>();
  const result: { name: string; importSpecifier: string }[] = [];
  for (const e of entries) {
    if (seen.has(e.name)) continue;
    seen.add(e.name);
    result.push(e);
  }
  result.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  return result;
}

/* ------------------------------------------------------------------ */
/*  Path computation                                                   */
/* ------------------------------------------------------------------ */

/**
 * Compute a posix-slashed relative import specifier from {@code .jsails/} to
 * the symbol's absolute file path.
 *
 * Example: symbol.file = {@code /project/app/composables/use-foo.ts},
 * jsailsDir = {@code /project} → result = {@code ../app/composables/use-foo.js}.
 *
 * The TypeScript source extension is rewritten to its compiled counterpart
 * (`.ts`/`.tsx` → `.js`, `.mts`/`.mtsx` → `.mjs`) so the declaration matches the
 * repo's ESM `.js`-specifier convention and resolves under `nodenext`.
 */
function relativeToJsails(jsailsDir: string, symbolFile: string): string {
  let rel = relative(jsailsDir, symbolFile);
  if (sep === '\\') {
    rel = rel.replace(/\\/g, '/');
  }

  rel = rel.replace(/\.(tsx|ts)$/, '.js').replace(/\.(mtsx|mts)$/, '.mjs');

  // The .jsails/ dir sits at project root, so relative() returns something like
  // `app/composables/use-foo.js` or `../outside/file.js`. For the .d.ts living
  // INSIDE .jsails/, we need prefix with `../` when the result does not start
  // with `..`.
  if (!rel.startsWith('.')) {
    rel = '../' + rel;
  }

  return rel;
}
