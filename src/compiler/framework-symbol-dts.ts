/**
 * Pure string builder for the generated ambient declarations.
 *
 * A JSails author writes `@jsails.maxLength(200)` and
 * `class Post extends ApplicationRecord` with no imports. TypeScript needs
 * global names to type-check those against; this emitter produces the
 * `.jsails/framework-symbols.d.ts` that supplies them.
 *
 * The file is a **script** — no top-level `import`/`export` — so its
 * `declare namespace jsails` and `declare const`/`declare type` names are true
 * globals rather than module-scoped. Type references use `import(...)` *type
 * queries*, which do not turn the file into a module.
 *
 * Two halves:
 *
 * 1. The `jsails` decorator namespace (the `@jsails.*` surface), whose runtime
 *    counterpart is {@link jsails} in `src/internal/jsails-namespace.ts`.
 * 2. The framework-symbol globals from {@link GenerateFrameworkSymbolsDtsOptions.globals} — the
 *    table derived at `build:meta` — each emitted as a **split value + type pair**. A `declare const X` is a value, not a
 *    type, so a bare `declare author: Author` would fail (`TS2749`); the paired
 *    `declare type X` supplies the type side. Both sides query the same export:
 *    `typeof import(spec).X` is the constructor/function type (value side), and
 *    `import(spec).X` is the instance type (type side for a class) or the
 *    function type (type side for a function).
 *
 * When a bare name collides (more than one entry declares it), the runtime
 * installer additionally publishes a **namespace object** — `content.readingTime`
 * — for each distinct subpath whose symbols collide. This emitter mirrors that
 * surface: the first-in-order entry keeps its bare split pair (it wins the bare
 * slot at runtime), and every colliding subpath additionally gets a
 * `declare const KEY: { SYM: typeof import('SPEC').SYM; ... }` object type, so
 * `KEY.sym` type-checks as property access — never a dotted key
 * (`first.sharedThing`). The namespace key is derived by the same
 * {@link deriveFrameworkSymbolNamespaceKeys} the installer uses, so the two can never drift.
 *
 * A test asserts the `jsails` namespace keys and the framework-global names stay
 * in sync with their runtime counterparts, so the two never drift.
 *
 * The emitter is pure: no I/O, no filesystem, no connection.
 */

import type { FrameworkSymbol } from '../symbols/framework-symbols.js';
import {
  computeFrameworkSymbolCollisionGroups,
  deriveFrameworkSymbolNamespaceKeys,
} from '../symbols/framework-symbols.js';

/* ------------------------------------------------------------------ */
/*  Header                                                             */
/* ------------------------------------------------------------------ */

const HEADER = '// AUTO-GENERATED by @jsails/compiler. Do not edit.\n\n';

/* ------------------------------------------------------------------ */
/*  Sections                                                           */
/* ------------------------------------------------------------------ */

/** The `jsails` decorator namespace, emitted as a merged const + namespace. */
function emitJsailsNamespace(): string {
  // The `enum` factory name is a reserved word, so it cannot be a bare
  // `function enum(...)` member of a `declare namespace`. The merged
  // `declare interface jsails` form lets a reserved-word method be declared with
  // a string-literal name (`["enum"](...)`) while the non-reserved methods stay
  // plain method signatures. `interface` + `namespace` merge in the ambient
  // global scope, so this reads identically to `jsails.maxLength(...)`.
  return `declare interface jsails {
  maxLength(length: number): PropertyDecorator;
  unique(): PropertyDecorator;
  nullable(): PropertyDecorator;
  encrypts(): PropertyDecorator;
  renamedFrom(previousName: string): PropertyDecorator;
  belongsTo(target: JsailsRelationTarget, options?: JsailsRelationOptions): PropertyDecorator;
  hasMany(target: JsailsRelationTarget, options?: JsailsRelationOptions): PropertyDecorator;
  hasOne(target: JsailsRelationTarget, options?: JsailsRelationOptions): PropertyDecorator;
  ["enum"](values: readonly (string | number)[]): PropertyDecorator;
}

declare namespace jsails {
  type JsailsRelationTarget = new (...args: never[]) => object;

  interface JsailsRelationOptions {
    touch?: boolean;
    counter_cache?: boolean;
    inverse?: string;
  }
}
`;
}

/** One split value+type declaration for a framework global. */
function emitFrameworkGlobal(name: string, specifier: string): string {
  return `declare const ${name}: typeof import('${specifier}').${name};
declare type ${name} = import('${specifier}').${name};`;
}

/**
 * Emit the bare split pair for every global, but only the **first-in-order**
 * entry for a colliding name — it is the one that wins the bare slot at
 * runtime. Colliding losers are reachable only through their namespace object.
 */
function emitBarePairs(
  globals: readonly FrameworkSymbol[],
  collidingNames: ReadonlySet<string>,
): string {
  const emittedBare = new Set<string>();
  const pairs: string[] = [];
  for (const { name, specifier } of globals) {
    if (collidingNames.has(name)) {
      if (emittedBare.has(name)) {
        continue;
      }
      emittedBare.add(name);
    }
    pairs.push(emitFrameworkGlobal(name, specifier));
  }
  return pairs.join('\n');
}

/** One namespace object type for a colliding specifier, keyed by derived key. */
function emitCollisionNamespace(
  key: string,
  specifier: string,
  symbols: readonly string[],
): string {
  const members = symbols
    .map((name) => `  ${name}: typeof import('${specifier}').${name};`)
    .join('\n');
  return `declare const ${key}: {\n${members}\n};`;
}

/**
 * Emit `declare const KEY: { ... }` namespace object types for every specifier
 * that participates in a collision. Value-side only: a matching `declare type`
 * alias would conflict with the `declare const` and is never required (access
 * is `KEY.sym`, and `typeof KEY.sym` serves as the type query).
 */
function emitCollisionDeclarations(
  globals: readonly FrameworkSymbol[],
  collisions: ReadonlyMap<string, readonly FrameworkSymbol[]>,
): string {
  if (collisions.size === 0) {
    return '';
  }

  const collidingNames = new Set(collisions.keys());

  // Specifiers that participate in at least one collision.
  const collidingSpecifiers = new Set<string>();
  for (const entries of collisions.values()) {
    for (const entry of entries) {
      collidingSpecifiers.add(entry.specifier);
    }
  }
  const namespaceKeys = deriveFrameworkSymbolNamespaceKeys(collidingSpecifiers);

  // Colliding symbol names per specifier (deduped; the runtime namespace object
  // keys a symbol once, so the object type must too).
  const symbolsBySpecifier = new Map<string, Set<string>>();
  for (const entry of globals) {
    if (collidingNames.has(entry.name)) {
      const symbols = symbolsBySpecifier.get(entry.specifier) ?? new Set<string>();
      symbols.add(entry.name);
      symbolsBySpecifier.set(entry.specifier, symbols);
    }
  }

  const decls: string[] = [];
  for (const specifier of [...collidingSpecifiers].sort()) {
    const key = namespaceKeys.get(specifier);
    if (key === undefined) {
      continue;
    }
    const symbolSet = symbolsBySpecifier.get(specifier);
    const symbols = symbolSet ? [...symbolSet].sort() : [];
    decls.push(emitCollisionNamespace(key, specifier, symbols));
  }
  return decls.join('\n');
}

/* ------------------------------------------------------------------ */
/*  Main entry point                                                   */
/* ------------------------------------------------------------------ */

/** Options for {@link generateFrameworkSymbolsDts}. The `globals` table is required. */
export interface GenerateFrameworkSymbolsDtsOptions {
  /** The global table to declare (derived at `build:meta` by the scan). */
  readonly globals: readonly FrameworkSymbol[];
}

/**
 * Generate the ambient declarations for `.jsails/framework-symbols.d.ts`. Deterministic:
 * the decorator namespace is fixed content, the framework globals follow the
 * supplied table's order, and any collision namespaces are sorted by specifier.
 */
export function generateFrameworkSymbolsDts(options: GenerateFrameworkSymbolsDtsOptions): string {
  const globals = options.globals;

  const collisions = computeFrameworkSymbolCollisionGroups(globals);
  const collidingNames = new Set(collisions.keys());

  const barePairs = emitBarePairs(globals, collidingNames);
  const collisionDecls = emitCollisionDeclarations(globals, collisions);

  const trailing = collisionDecls.length > 0 ? `\n${collisionDecls}` : '';
  return `${HEADER}${emitJsailsNamespace()}\n${barePairs}${trailing}\n`;
}
