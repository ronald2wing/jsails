/**
 * Pure emitter for the generated framework-symbol runtime module.
 *
 * The framework-symbol globals have two halves, both generated at `build:meta`
 * time from the framework's own barrels:
 *
 * - `.jsails/framework-symbols.d.ts` — the ambient declarations `tsc` checks
 *   bare names against (see {@link generateFrameworkSymbolsDts}).
 * - `.jsails/framework-symbols.js` — the runtime symbol table the installer
 *   projects onto `globalThis` (this module).
 *
 * The runtime module is **pure data**: a frozen literal array of
 * `{ name, specifier, target }` entries. It carries no projection logic — the
 * installer (`installFrameworkSymbols`) owns that, so the collision policy and
 * the namespace derivation live in exactly one place. The module is emitted
 * rather than checked in so it can never drift from the barrels it describes.
 *
 * The declaration is resolved **here**, at emit time: `all` (the default)
 * projects every subpath, `selected` narrows to the named specifiers, `none`
 * projects nothing. The runtime installer receives the already-filtered table,
 * so no declaration logic runs at process start.
 *
 * The emitter is pure: no I/O, no filesystem, no connection.
 */

import type { FrameworkSymbol } from '../symbols/framework-symbols.js';

/* ------------------------------------------------------------------ */
/*  Header                                                             */
/* ------------------------------------------------------------------ */

const HEADER = '// AUTO-GENERATED by jsails build:meta. Do not edit.\n\n';

/* ------------------------------------------------------------------ */
/*  Emit                                                               */
/* ------------------------------------------------------------------ */

/**
 * Emit `.jsails/framework-symbols.js`: the runtime symbol table as a frozen
 * literal. Deterministic — entries keep the scan's order (specifier-sorted,
 * barrel order within a subpath), so the emitted file is byte-stable across
 * runs and the installer's collision policy sees a stable table order.
 *
 * An empty table emits `export const FRAMEWORK_SYMBOLS = [];` — a valid module
 * the installer reads as "project nothing", never a missing-file error.
 */
export function emitFrameworkSymbolsModule(globals: readonly FrameworkSymbol[]): string {
  const entries = globals
    .map(
      (entry) =>
        `  { name: ${quote(entry.name)}, specifier: ${quote(entry.specifier)}, target: ${quote(entry.target)} },`,
    )
    .join('\n');

  const body = entries.length > 0 ? `[\n${entries}\n]` : '[]';
  return `${HEADER}export const FRAMEWORK_SYMBOLS = Object.freeze(${body});\n`;
}

/** Single-quote a string literal, escaping the characters that can appear. */
function quote(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}
