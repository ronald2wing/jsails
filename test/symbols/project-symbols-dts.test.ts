import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import type {
  AutoloadContext,
  AutoloadRegistry,
  AutoloadCollisionMap,
  AutoloadSymbol,
} from '../../src/compiler/project-symbols-scan.js';
import { generateProjectSymbolsDts } from '../../src/compiler/project-symbols-dts.js';
import { deriveFrameworkSymbolNamespaceKeys } from '../../src/symbols/framework-symbols.js';

/** Build a minimal registry shape from `[name, context, absoluteFile]` triples. */
function registry(
  entries: readonly (readonly [string, AutoloadContext, string])[],
  collisions: AutoloadCollisionMap = new Map(),
): AutoloadRegistry {
  const byName = new Map<string, Map<AutoloadContext, AutoloadSymbol>>();
  for (const [name, context, file] of entries) {
    let contexts = byName.get(name);
    if (contexts === undefined) {
      contexts = new Map();
      byName.set(name, contexts);
    }
    contexts.set(context, { name, context, file });
  }
  return { entries: [], byName, collisions };
}

/** Build a collision entry: winner first, then losers. */
function collision(
  name: string,
  ...symbols: readonly (readonly [AutoloadContext, string])[]
): [string, readonly AutoloadSymbol[]] {
  return [name, symbols.map(([context, file]) => ({ name, context, file }))];
}

describe('generateProjectSymbolsDts', () => {
  it('emits an app declaration for an app symbol with a .js specifier', () => {
    const files = generateProjectSymbolsDts(
      registry([['useCounter', 'app', '/proj/app/composables/use-counter.ts']]),
      { rootDir: '/proj' },
    );

    assert.match(
      files['project-symbols.app.d.ts'],
      /const useCounter: typeof import\('\.\.\/app\/composables\/use-counter\.js'\)\.useCounter;/,
    );
  });

  it('emits a split value + type pair so a bare type reference resolves', () => {
    const files = generateProjectSymbolsDts(
      registry([['Author', 'server', '/proj/models/author.ts']]),
      {
        rootDir: '/proj',
      },
    );

    const body = files['project-symbols.server.d.ts'];
    assert.match(body, /const Author: typeof import\('\.\.\/models\/author\.js'\)\.Author;/);
    assert.match(body, /type Author = import\('\.\.\/models\/author\.js'\)\.Author;/);
  });

  it('emits a server declaration for a server symbol', () => {
    const files = generateProjectSymbolsDts(
      registry([['serverOnlyFn', 'server', '/proj/server/utils/server-only-fn.ts']]),
      { rootDir: '/proj' },
    );

    assert.match(
      files['project-symbols.server.d.ts'],
      /const serverOnlyFn: typeof import\('\.\.\/server\/utils\/server-only-fn\.js'\)\.serverOnlyFn;/,
    );
  });

  it('keeps app and server symbols in their own files', () => {
    const files = generateProjectSymbolsDts(
      registry([
        ['useCounter', 'app', '/proj/app/composables/use-counter.ts'],
        ['serverOnlyFn', 'server', '/proj/server/utils/server-only-fn.ts'],
      ]),
      { rootDir: '/proj' },
    );

    assert.match(files['project-symbols.app.d.ts'], /useCounter/);
    assert.doesNotMatch(files['project-symbols.app.d.ts'], /serverOnlyFn/);
    assert.match(files['project-symbols.server.d.ts'], /serverOnlyFn/);
    assert.doesNotMatch(files['project-symbols.server.d.ts'], /useCounter/);
  });

  it('sorts declarations by name for deterministic output', () => {
    const files = generateProjectSymbolsDts(
      registry([
        ['zebra', 'app', '/proj/app/utils/zebra.ts'],
        ['alpha', 'app', '/proj/app/utils/alpha.ts'],
        ['middle', 'app', '/proj/app/utils/middle.ts'],
      ]),
      { rootDir: '/proj' },
    );

    const body = files['project-symbols.app.d.ts'];
    const alphaAt = body.indexOf('alpha');
    const middleAt = body.indexOf('middle');
    const zebraAt = body.indexOf('zebra');
    assert.ok(alphaAt < middleAt && middleAt < zebraAt);
  });

  it('emits a valid empty stub when a context has no symbols', () => {
    const files = generateProjectSymbolsDts(registry([]), { rootDir: '/proj' });

    assert.equal(
      files['project-symbols.app.d.ts'],
      '// AUTO-GENERATED by @jsails/compiler. Do not edit.\n\ndeclare global {\n}\nexport {};\n',
    );
    assert.equal(
      files['project-symbols.server.d.ts'],
      '// AUTO-GENERATED by @jsails/compiler. Do not edit.\n\ndeclare global {\n}\nexport {};\n',
    );
  });

  it('wraps declarations in a global augmentation with an export marker', () => {
    const files = generateProjectSymbolsDts(
      registry([['useCounter', 'app', '/proj/app/composables/use-counter.ts']]),
      { rootDir: '/proj' },
    );

    const body = files['project-symbols.app.d.ts'];
    assert.match(body, /declare global \{/);
    assert.match(body, /export \{\};/);
  });

  it('is deterministic across repeated calls', () => {
    const reg = registry([
      ['b', 'app', '/proj/app/utils/b.ts'],
      ['a', 'app', '/proj/app/utils/a.ts'],
    ]);
    const first = generateProjectSymbolsDts(reg, { rootDir: '/proj' });
    const second = generateProjectSymbolsDts(reg, { rootDir: '/proj' });
    assert.deepEqual(first, second);
  });

  describe('collisions', () => {
    it('emits a namespace type declaration for a colliding name', () => {
      const files = generateProjectSymbolsDts(
        registry(
          [['Thing', 'server', '/proj/models/thing.ts']],
          new Map([
            collision(
              'Thing',
              ['server', '/proj/models/thing.ts'],
              ['server', '/proj/server/models/thing.ts'],
            ),
          ]),
        ),
        { rootDir: '/proj' },
      );

      const body = files['project-symbols.server.d.ts'];
      // The bare winner pair is still present.
      assert.match(body, /const Thing: typeof import\('\.\.\/models\/thing\.js'\)\.Thing;/);
      assert.match(body, /type Thing = import\('\.\.\/models\/thing\.js'\)\.Thing;/);
      // The namespace type for the winner's path: `models/thing` → last-segment key `thing`.
      assert.match(body, /const thing: \{/);
      assert.match(body, /Thing: typeof import\('\.\.\/models\/thing\.js'\)\.Thing;/);
    });

    it('uses the same namespace key as deriveFrameworkSymbolNamespaceKeys', () => {
      const files = generateProjectSymbolsDts(
        registry(
          [['Fn', 'app', '/proj/app/utils/fn.ts']],
          new Map([
            collision('Fn', ['app', '/proj/app/utils/fn.ts'], ['app', '/proj/server/utils/fn.ts']),
          ]),
        ),
        { rootDir: '/proj' },
      );

      const expectedKey = deriveFrameworkSymbolNamespaceKeys(['app/utils/fn']).get('app/utils/fn');
      assert.ok(expectedKey, 'namespace key exists');
      // The `.d.ts` file declares `const <key>: { ... };`.
      const body = files['project-symbols.app.d.ts'];
      assert.match(body, new RegExp(`const ${expectedKey}: \\{`));
    });

    it('does not emit a namespace when a collision is in a different context', () => {
      const files = generateProjectSymbolsDts(
        registry(
          [['Thing', 'server', '/proj/models/thing.ts']],
          new Map([
            collision(
              'Thing',
              ['app', '/proj/app/utils/thing.ts'],
              ['app', '/proj/server/app/utils/thing.ts'],
            ),
          ]),
        ),
        { rootDir: '/proj' },
      );

      // The server context has no collision — bare winner only.
      const body = files['project-symbols.server.d.ts'];
      assert.match(body, /const Thing:/);
      assert.doesNotMatch(body, /const utils:/);
    });

    it('emits unchanged output when there are no collisions', () => {
      const reg = registry([['Author', 'server', '/proj/models/author.ts']]);
      const files = generateProjectSymbolsDts(reg, { rootDir: '/proj' });

      const body = files['project-symbols.server.d.ts'];
      assert.match(body, /const Author:/);
      assert.match(body, /type Author =/);
      // No namespace lines.
      assert.doesNotMatch(body, /\n  const \w+: \{/);
    });

    it('is deterministic with collisions present', () => {
      const reg = registry(
        [['Thing', 'server', '/proj/models/thing.ts']],
        new Map([
          collision(
            'Thing',
            ['server', '/proj/models/thing.ts'],
            ['server', '/proj/server/models/thing.ts'],
          ),
        ]),
      );
      const first = generateProjectSymbolsDts(reg, { rootDir: '/proj' });
      const second = generateProjectSymbolsDts(reg, { rootDir: '/proj' });
      assert.deepEqual(first, second);
    });
  });
});
